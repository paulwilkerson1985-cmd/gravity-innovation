// ---------------------------------------------------------------- accented letters (composed)
type Mark = { lo: string; hi: string[] };
const MARKS: Record<string, Mark> = {
  acute: { lo: '..#.', hi: ['...#.', '..#..'] },
  grave: { lo: '.#..', hi: ['.#...', '..#..'] },
  circ: { lo: '.##.', hi: ['..#..', '.#.#.'] },
  diaer: { lo: '#..#', hi: ['.....', '#..#.'] },
  tilde: { lo: '##.#', hi: ['.#.#.', '#.#..'] },
  ring: { lo: '.##.', hi: ['.#...', '#.#..'] },
};

function fit(pattern: string, w: number): string {
  // centre a mark pattern over a glyph of width w
  const p = pattern.replace(/\.+$/, '');
  if (p.length >= w) return p.slice(0, w).padEnd(w, '.');
  const left = Math.max(0, Math.floor((w - pattern.length) / 2));
  return ('.'.repeat(left) + pattern).slice(0, w).padEnd(w, '.');
}

function composeLower(base: string, mark: keyof typeof MARKS): GlyphDef {
  const b = GLYPHS[base]!;
  const w = b.rows[0]!.length;
  const rows = [...b.rows];
  rows[0] = fit(MARKS[mark]!.lo, w);
  return { rows };
}

function composeUpper(base: string, mark: keyof typeof MARKS): GlyphDef {
  const b = GLYPHS[base]!;
  const w = b.rows[0]!.length;
  return { rows: [...MARKS[mark]!.hi.map((r) => fit(r.slice(0, Math.max(w, 4)), w)), ...b.rows] };
}

