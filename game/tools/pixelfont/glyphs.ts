// "Orbkin Pixel" — the game's own bitmap font (project-owned, see ASSETS.md).
//
// Grid: 1 font pixel = 100 units, 1000 units per em, so `font-size: 10px` draws 1 CSS px per
// font pixel, 20px draws 2, 30px draws 3 (always use multiples of 10px for crisp text).
// Cap height 7, x-height 5, descender 2, ascent 8 / descent 2.
//
// Each glyph is a list of rows, top to bottom, starting at the cap line (y = 6) and padded
// below to the descender (y = -2). '#' = ink. A glyph with more than 9 rows grows upward
// (accented capitals). The advance is the width + 1 px of spacing unless `adv` says otherwise.

export interface GlyphDef { rows: string[]; adv?: number }

const g = (spec: string, adv?: number): GlyphDef => ({ rows: spec.trim().split(/\s+/), ...(adv !== undefined ? { adv } : {}) });
/** Rows given relative to the x-height: two empty rows are added on top. */
const lo = (spec: string): GlyphDef => {
  const rows = spec.trim().split(/\s+/);
  const w = rows[0]!.length;
  return { rows: ['.'.repeat(w), '.'.repeat(w), ...rows] };
};

